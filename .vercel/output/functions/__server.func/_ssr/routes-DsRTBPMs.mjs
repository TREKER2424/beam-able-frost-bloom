	roleOk(outRole, inRole) {
		if (outRole === "GK" || inRole === "GK") return outRole === inRole;
		const rank = (r) => r === "ST" || r === "LW" || r === "RW" ? 3 : r === "CAM" ? 2 : r === "CB" || r === "LB" || r === "RB" ? 0 : 1;
		return Math.abs(rank(outRole) - rank(inRole)) <= 2;
	}
