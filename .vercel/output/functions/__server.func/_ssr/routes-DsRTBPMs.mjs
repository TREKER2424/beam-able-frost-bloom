		inn.slot = out.slot;
		inn.x = out.x;
		inn.y = out.y;
		inn.vx = 0;
		inn.vy = 0;
		inn.stamina = Math.min(100, inn.maxStamina);
		out.on = false;
		out.slot = -1;
		out.vx = 0;
		out.vy = 0;
